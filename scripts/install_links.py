#!/usr/bin/env python3
"""Generate every one-step install surface from one set of facts.

Writes the MCP Registry entry (server.json), the Claude Desktop bundle source
(mcpb/manifest.json, mcpb/pyproject.toml), and the install section of both
READMEs (the repository README and the PyPI page, mcp-server/README.md), with
the Cursor and VS Code install links encoded from the same launch command.
Hand edits to those parts drift; edit the facts here and rerun.

    python3 scripts/install_links.py          # rewrite the generated files
    python3 scripts/install_links.py --check  # exit 1 if any is stale (CI)

Why the launch command pins Python 3.12: python-rtmidi 1.5.8, the MIDI
dependency, publishes wheels only up to CPython 3.12. uvx otherwise picks the
newest Python it finds (it ignores the package's requires-python), and on
3.13+ it compiles rtmidi from source, which fails on a machine without a C++
toolchain (most Windows machines).
"""

from __future__ import annotations

import base64
import json
import re
import sys
import tomllib
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PACKAGE = "fl-studio-agent"
SERVER_KEY = "fl-studio"  # the name clients list it under; matches the server's serverInfo.name
REGISTRY_NAME = "io.github.origami-research/fl-studio-agent"
REPO_URL = "https://github.com/origami-research/fl-studio-agent"
TITLE = "FL Studio Agent"
DESCRIPTION = "Drive FL Studio from an AI agent: write notes, set tempo and levels, check what sounds, render."
PYTHON = "3.12"
BUNDLE_PYTHON = ">=3.11,<3.13"  # the bundle's uv honors a project's requires-python
UVX_ARGS = ["--python", PYTHON]
LAUNCH = ["uvx", *UVX_ARGS, PACKAGE]
SETUP_COMMAND = f"uvx --python {PYTHON} --from {PACKAGE} fl-mcp-install"
DOCTOR_COMMAND = f"uvx --python {PYTHON} --from {PACKAGE} fl-mcp-doctor"
BUNDLE_ASSET = f"{PACKAGE}.mcpb"
BUNDLE_URL = f"{REPO_URL}/releases/latest/download/{BUNDLE_ASSET}"
REGISTRY_SCHEMA = "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json"

START = "<!-- install:start (generated by scripts/install_links.py; edit there) -->"
END = "<!-- install:end -->"


def version() -> str:
    with (ROOT / "mcp-server" / "pyproject.toml").open("rb") as fh:
        return tomllib.load(fh)["project"]["version"]


def server_config() -> dict:
    """The stdio server entry every client's config holds under SERVER_KEY."""
    return {"command": LAUNCH[0], "args": LAUNCH[1:]}


def cursor_link() -> str:
    # Cursor's install link carries base64 of the inner server object (no mcpServers wrapper).
    config = base64.b64encode(json.dumps(server_config(), separators=(",", ":")).encode()).decode()
    return f"https://cursor.com/en/install-mcp?name={SERVER_KEY}&config={urllib.parse.quote(config, safe='')}"


def vscode_link() -> str:
    # The redirect turns this into vscode:mcp/install?{"name":...,"type":"stdio",...}.
    config = json.dumps({"type": "stdio", **server_config()}, separators=(",", ":"))
    return f"https://insiders.vscode.dev/redirect/mcp/install?name={SERVER_KEY}&config={urllib.parse.quote(config, safe='')}"


def vscode_cli() -> str:
    return "code --add-mcp '" + json.dumps({"name": SERVER_KEY, "type": "stdio", **server_config()}) + "'"


def mcp_servers_json() -> str:
    return json.dumps({"mcpServers": {SERVER_KEY: server_config()}}, indent=2)


def server_json(ver: str) -> dict:
    """The MCP Registry entry. PyPI ownership is proven by the mcp-name line on the PyPI page."""
    return {
        "$schema": REGISTRY_SCHEMA,
        "name": REGISTRY_NAME,
        "title": TITLE,
        "description": DESCRIPTION,
        "repository": {"url": REPO_URL, "source": "github"},
        "version": ver,
        "packages": [
            {
                "registryType": "pypi",
                "registryBaseUrl": "https://pypi.org",
                "identifier": PACKAGE,
                "version": ver,
                "runtimeHint": "uvx",
                "runtimeArguments": [{"type": "named", "name": "--python", "value": PYTHON}],
                "transport": {"type": "stdio"},
                "environmentVariables": [
                    {
                        "name": "FLMCP_FL_LICENSE",
                        "description": "Set to 'trial' when FL Studio runs as the unregistered trial "
                        "(it cannot reopen saved projects); 'licensed' otherwise.",
                        "isRequired": False,
                        "default": "licensed",
                        "choices": ["licensed", "trial"],
                    }
                ],
            }
        ],
    }


def bundle_manifest(ver: str) -> dict:
    """Claude Desktop bundle: a uv-runtime shim whose pyproject pins this release from PyPI,
    so the host's uv installs the same package every other client runs."""
    return {
        "manifest_version": "0.4",
        "name": PACKAGE,
        "display_name": TITLE,
        "version": ver,
        "description": DESCRIPTION,
        "long_description": (
            "Lets Claude write notes into FL Studio, set tempo, levels and plugin parameters, check which "
            "channels sound, and render the mix to WAV. Before first use, close FL Studio and run "
            f"`{SETUP_COMMAND}` once (on Windows from an administrator terminal): it installs the FL-side scripts "
            "and the prebuilt, checksum-verified Bridge plugin that live writes and rendering use. "
            f"Setup guide: {REPO_URL}#quick-start"
        ),
        "author": {"name": "Origami Research", "url": REPO_URL},
        "repository": {"type": "git", "url": f"{REPO_URL}.git"},
        "homepage": REPO_URL,
        "documentation": f"{REPO_URL}/blob/main/SETUP.md",
        "support": f"{REPO_URL}/issues",
        "license": "MIT",
        "keywords": ["fl-studio", "music", "daw", "midi"],
        "server": {
            "type": "uv",
            "entry_point": "src/server.py",
            "mcp_config": {
                "command": "uv",
                "args": ["run", "--directory", "${__dirname}", "src/server.py"],
                "env": {"FLMCP_FL_LICENSE": "${user_config.fl_license}"},
            },
        },
        "user_config": {
            "fl_license": {
                "type": "string",
                "title": "FL Studio license",
                "description": "'licensed', or 'trial' for the unregistered trial (it cannot reopen saved projects).",
                "default": "licensed",
                "required": False,
            }
        },
        "compatibility": {"platforms": ["darwin", "win32"], "runtimes": {"python": BUNDLE_PYTHON}},
    }


def bundle_pyproject(ver: str) -> str:
    return (
        "# Generated by scripts/install_links.py. The Claude Desktop bundle's uv runtime installs\n"
        "# this release from PyPI; requires-python keeps it on a Python with python-rtmidi wheels.\n"
        "[project]\n"
        f'name = "{PACKAGE}-bundle"\n'
        f'version = "{ver}"\n'
        f'requires-python = "{BUNDLE_PYTHON}"\n'
        f'dependencies = ["{PACKAGE}=={ver}"]\n'
    )


def install_section() -> str:
    """The install section both READMEs carry. Links are absolute so the PyPI copy works."""
    claude_code = f"claude mcp add --scope user {SERVER_KEY} -- {' '.join(LAUNCH)}"
    return f"""{START}
[![Install in Cursor](https://cursor.com/deeplink/mcp-install-dark.svg)]({cursor_link()})
[![Install in VS Code](https://img.shields.io/badge/VS_Code-Install_Server-0098FF?style=flat-square&logo=visualstudiocode&logoColor=white)]({vscode_link()})
[![Claude Desktop bundle](https://img.shields.io/badge/Claude_Desktop-Download_bundle-D97757?style=flat-square&logo=claude&logoColor=white)]({BUNDLE_URL})
[![PyPI](https://img.shields.io/pypi/v/{PACKAGE}?style=flat-square)](https://pypi.org/project/{PACKAGE}/)
[![License: MIT](https://img.shields.io/badge/license-MIT-blue?style=flat-square)]({REPO_URL}/blob/main/LICENSE)

**Claude Code:**

```bash
{claude_code}
```

## Quick start

You need FL Studio 2026 on macOS or Windows and [uv](https://docs.astral.sh/uv/getting-started/installation/).

1. **Install uv** if you don't have it.
   macOS: `curl -LsSf https://astral.sh/uv/install.sh | sh`.
   Windows: `powershell -ExecutionPolicy ByPass -c "irm https://astral.sh/uv/install.ps1 | iex"`, then install [loopMIDI](https://www.tobias-erichsen.de/software/loopmidi.html) and add two ports named exactly `FLMCP Req` and `FLMCP Res` (Windows has no virtual MIDI ports; macOS needs nothing).
2. **Set up FL Studio once.** Start FL once if you never have, close it, then run (on Windows, in a terminal opened as administrator, because FL's plugin folder is under Program Files):

   ```bash
   {SETUP_COMMAND}
   ```

   It installs the controller and note scripts, assigns the controller's MIDI ports, creates the agent's own project (`FLMCP Agent.flp`; your other projects are never touched), and downloads the prebuilt [Bridge plugin]({REPO_URL}/blob/main/SETUP.md#the-bridge-plugin) for live writes and `render`, checking it against the release's SHA-256 sums.
   It is safe to rerun.
   To update later, run it with `{PACKAGE}@latest` in place of `{PACKAGE}` and restart FL and your client.
3. **Add the server to your client** with a button above or a config below, open FL Studio, and ask for "a 4-bar chord loop in A minor".

<details>
<summary><b>Claude Code</b></summary>

```bash
{claude_code}
```

Check it with `claude mcp list`.
</details>

<details>
<summary><b>Claude Desktop</b></summary>

Download [{BUNDLE_ASSET}]({BUNDLE_URL}) and open it (or drag it into Settings > Extensions).
Claude Desktop installs the package itself; you still run step 2 once, which also installs the Bridge plugin into FL.

Or add this to `claude_desktop_config.json` (Settings > Developer > Edit Config):

```json
{mcp_servers_json()}
```

If Claude Desktop reports `spawn uvx ENOENT`, it cannot see your shell's PATH: replace `"uvx"` with the full path that `which uvx` (macOS) or `where uvx` (Windows) prints.
</details>

<details>
<summary><b>Cursor</b></summary>

Use the **Install in Cursor** button above, or add this to `~/.cursor/mcp.json`:

```json
{mcp_servers_json()}
```
</details>

<details>
<summary><b>VS Code</b></summary>

Use the **Install in VS Code** button above, or run (macOS/Linux shell quoting):

```bash
{vscode_cli()}
```
</details>

<details>
<summary><b>Windsurf and other clients</b></summary>

Add the standard entry to the client's MCP config (Windsurf: `mcp_config.json`, see [its MCP docs](https://docs.windsurf.com/windsurf/cascade/mcp)):

```json
{mcp_servers_json()}
```
</details>

## Troubleshooting

Run the doctor while FL Studio is open:

```bash
{DOCTOR_COMMAND}
```

It prints one JSON report of the control plane (controller script and MIDI ports), the note plane, and the agent project, with a `fix` for anything not connected.
The usual fixes: open FL Studio before your client starts the server; after an upgrade rerun step 2 with `{PACKAGE}@latest` (a stale controller is reported); on Windows, keep loopMIDI running with both ports.
Using the FL Studio trial? Set `FLMCP_FL_LICENSE=trial` in the server's `env`, because the trial cannot reopen saved projects.
`uvx --python {PYTHON} {PACKAGE} --version` prints the installed version.
{END}"""


def replace_section(text: str, section: str) -> str:
    pattern = re.compile(re.escape(START.split(" (")[0]) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit("missing the install:start/install:end markers")
    return pattern.sub(lambda _m: section, text, count=1)


def outputs() -> dict[Path, str]:
    ver = version()
    section = install_section()
    return {
        ROOT / "server.json": json.dumps(server_json(ver), indent=2) + "\n",
        ROOT / "mcpb" / "manifest.json": json.dumps(bundle_manifest(ver), indent=2) + "\n",
        ROOT / "mcpb" / "pyproject.toml": bundle_pyproject(ver),
        ROOT / "README.md": replace_section((ROOT / "README.md").read_text(encoding="utf-8"), section),
        ROOT / "mcp-server" / "README.md": replace_section(
            (ROOT / "mcp-server" / "README.md").read_text(encoding="utf-8"), section
        ),
    }


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print(__doc__)
        return 2
    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if check and stale:
        print("stale install surfaces (run python3 scripts/install_links.py):", *stale, sep="\n  ")
        return 1
    print("updated: " + ", ".join(map(str, stale)) if stale else "install surfaces are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
