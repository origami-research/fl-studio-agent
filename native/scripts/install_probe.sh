#!/usr/bin/env bash
# Install the FL MCP Probe diagnostic plugin into FL Studio's native effects
# folder. This is a THROWAWAY diagnostic (see native/probe/RUNBOOK_PROBE.md),
# not a production component - install it on a scratch machine/project, run the
# passes, record the verdict, then uninstall.
#
# Same mechanics as install_bridge.sh: FL loads unsigned native plugins from
# inside its own bundle (group-writable, no sudo; disable-library-validation
# entitlement lets an unsigned dylib load). The Probe is an EFFECT and has no
# UI; loading it on any mixer insert starts its extended tick.
#
# It ALSO mints the plugin-database entry (a .fst), because a dylib alone does
# not appear in FL's browser: that normally needs "Manage plugins > Find
# installed plugins" plus a restart. The .fst is generated byte-exactly by
# native/probe/make_fst.py (which proves itself against entries FL wrote), so
# the Probe is insertable immediately, with no rescan and no restart.
#
# Usage: install_probe.sh [--uninstall] [--folder Effects|Generators] [--no-db-entry]
# FL_APP overrides FL.app auto-detection; FL_USER_DATA overrides the user data
# folder the .fst goes into.
set -euo pipefail

ACTION="install"
FOLDER="Effects"
DB_ENTRY=1
while [ $# -gt 0 ]; do
    case "$1" in
        --uninstall)   ACTION="uninstall"; shift ;;
        --folder)      FOLDER="$2"; shift 2 ;;
        --no-db-entry) DB_ENTRY=0; shift ;;
        *) echo "unknown option: $1" >&2; exit 1 ;;
    esac
done
case "$FOLDER" in
    Effects|Generators) ;;
    *) echo "unknown --folder '$FOLDER' (want: Effects | Generators)" >&2; exit 1 ;;
esac

NAME="FL MCP Probe"
DYLIB="${NAME}_x64.dylib"
NATIVE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD="$NATIVE_DIR/build/$DYLIB"

if [ -z "${FL_APP:-}" ]; then
    FL_APP="$(ls -d "/Applications/FL Studio"*.app 2>/dev/null | sort -V | tail -1)"
fi
if [ -z "${FL_APP:-}" ] || [ ! -d "$FL_APP" ]; then
    echo "No FL Studio.app found under /Applications. Set FL_APP=/path/to/FL Studio.app." >&2
    exit 1
fi

PLUGDIR="$FL_APP/Contents/Resources/FL/Plugins/Fruity/$FOLDER"
DEST="$PLUGDIR/$NAME"

FL_USER_DATA="${FL_USER_DATA:-$HOME/Documents/Image-Line/FL Studio}"
DB_DIR="$FL_USER_DATA/Presets/Plugin database/$FOLDER"
FST="$DB_DIR/$NAME.fst"

if [ "$ACTION" = "uninstall" ]; then
    rm -rf "$DEST"
    echo "Removed $DEST"
    rm -f "$FST" && echo "Removed $FST"
    exit 0
fi

if [ ! -d "$PLUGDIR" ]; then
    echo "FL Studio $FOLDER folder not found: $PLUGDIR" >&2
    exit 1
fi
if [ ! -f "$BUILD" ]; then
    echo "Not built yet. Run:" >&2
    echo "  native/scripts/fetch_sdk.sh" >&2
    echo "  cmake -S native -B native/build -DCMAKE_BUILD_TYPE=Release" >&2
    echo "  cmake --build native/build --target probe" >&2
    exit 1
fi

mkdir -p "$DEST"
cp "$BUILD" "$DEST/$DYLIB"
printf 'ps_Vendorname=FL MCP\n' > "$DEST/Plugin.nfo"
xattr -d com.apple.quarantine "$DEST/$DYLIB" 2>/dev/null || true

echo "Installed: $DEST/$DYLIB"
echo "  type:   FPF_Type_Effect (base-free, 64-slot ABI)"

if [ "$DB_ENTRY" = "1" ]; then
    python3 "$NATIVE_DIR/probe/make_fst.py" --name "$NAME" --folder "$FOLDER" --out "$FST"
    # The 2026-08-29 window was lost to a misclick on a stale sibling entry, so
    # say out loud what else is in that folder wearing a similar name.
    SIBLINGS="$(ls "$DB_DIR" 2>/dev/null | grep -i '^FL MCP' | grep -v "^$NAME.fst$" || true)"
    if [ -n "$SIBLINGS" ]; then
        echo
        echo "WARNING - other FL MCP entries in $DB_DIR:"
        echo "$SIBLINGS" | sed 's/^/  /'
        echo "  Any 'Spike1' entry is a known-broken v1 plugin that crashes FL."
        echo "  Prefer the click-free route below so you never pick from this list."
    fi
fi

echo
echo "Next - CLICK-FREE (preferred), no plugin list to misread:"
echo "  native/probe/stamp_probe_project.py \\"
echo "      --source <a project with 'FL MCP Bridge' on a mixer insert> \\"
echo "      --out    \"\$HOME/Documents/Image-Line/FL Studio/Projects/PROBE Scratch.flp\""
echo "  then open 'PROBE Scratch.flp' in FL. The Probe loads with the project."
echo
echo "Fallback (one time only, then save as PROBE Scratch.flp):"
echo "  Mixer (F9) > select an insert > add effect > '$NAME'  <- read the name carefully"
echo "Then follow native/probe/RUNBOOK_PROBE.md."
