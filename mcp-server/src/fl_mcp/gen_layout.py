"""Profile -> generated native header: the ABI facts, compiled in, not parsed.

The plugin must not parse JSON at load time to learn its own ABI - a wrong
layout must fail the BUILD, not FL (docs/research/r4-streamline-and-audit.md
§A1 "The native side: generated, not parsed"). This generator emits
``native/generated/fl_profile_generated.h`` from a profile document: the
``static_assert`` wall that pins the fetched SDK header against the layout
scraped from FL's own binary, plus the version-specific constants
(``kHandledMaxId``, ``kDefaultPPQ``, the VMT first-method offset, the
unsafe-id ledger). It REPLACES the hand-maintained block in bridge_core.cpp
and the literals in probe_safety.h - those numbers now have one home.

Output is deterministic (no timestamps): the checked-in header must
regenerate byte-for-byte from the packaged profile (test_gen_layout.py pins
this), so CMake can re-run the generator without churning the tree.

CLI: ``python -m fl_mcp.gen_layout <profile.json> [-o <out.h>]``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Only the records the native ABI actually hands FL are pinned with asserts;
# the profile may carry more (TFruityPlugInfo) for evidence and scraping.
ASSERTED_STRUCTS = ("TNoteParams", "TNotesParams")

# RTTI type name -> byte width, for per-field size asserts. This is what turns
# "Vol is Single" into a build-time fact even though the C++ header says int.
_TYPE_WIDTH = {"LongInt": 4, "Single": 4, "SmallInt": 2, "PChar": 8}


class GenError(ValueError):
    """The profile document lacks something the header cannot be emitted without."""


def _validate(doc: dict) -> None:
    """Semantic guards that must fail LOUDLY, not be swallowed as "malformed":
    an empty ledger would silently unlearn the crashers; a missing asserted
    struct would drop its layout wall."""
    dispatcher = doc.get("dispatcher", {}) if isinstance(doc, dict) else {}
    if not dispatcher.get("unsafe"):
        raise GenError("dispatcher.unsafe is empty - refusing to emit a ledger that unlearns 94/99")
    structs = doc.get("structs", {})
    for name in ASSERTED_STRUCTS:
        if name not in structs:
            raise GenError(f"profile has no structs[{name!r}] - cannot emit its assert wall")


def generate(doc: dict) -> str:
    """The full header text for one profile document. Deterministic."""
    _validate(doc)
    try:
        meta = doc["meta"]
        dispatcher = doc["dispatcher"]
        structs = doc["structs"]
        ppq_default = int(doc["ppq"]["default"])
        provenance = (
            f"FL {meta['fl_version']} build {meta['fl_build']} {meta['arch']}, "
            f"engine sha256 {meta['engine_dylib_sha256']}"
        )
        unsafe = sorted(dispatcher["unsafe"], key=lambda u: int(u["id"]))
        lines = [
            "// fl_profile_generated.h - GENERATED by python -m fl_mcp.gen_layout. DO NOT EDIT.",
            f"// Source profile: {provenance}.",
            "// A new FL version means: run discovery, get a new profile, regenerate, rebuild -",
            "// zero hand edits. Regenerate with:",
            "//   python -m fl_mcp.gen_layout mcp-server/src/fl_mcp/profiles/<profile>.json \\",
            "//     -o native/generated/fl_profile_generated.h",
            "//",
            "// Contract with the native side (docs/27 §6): this header includes NOTHING of",
            "// the SDK. The struct-assert wall below only materializes in the one TU that",
            "// defines FLMCP_ASSERT_STRUCTS after including fp_plugclass.h.",
            "#ifndef FLMCP_PROFILE_GENERATED_H",
            "#define FLMCP_PROFILE_GENERATED_H",
            "#define FLMCP_PROFILE_GENERATED 1",
            "",
            "namespace fl_profile {",
            "",
            "// The highest dispatcher id FL handles: ids past this take the jump table's",
            "// default branch and are inert by decode.",
            f"inline constexpr int kHandledMaxId = {int(dispatcher['handled_max_id'])};",
            "",
            "// Last-resort PPQ only; commands carry a ppq stamp.",
            f"inline constexpr int kDefaultPPQ = {ppq_default};",
            "",
            "// Live-confirmed fatal dispatcher ids: skipped by construction. Static in the",
            "// build (a crasher must never depend on runtime parsing), but the SOURCE is",
            "// the profile's dispatcher.unsafe block, so a new version's crashers flow in",
            "// without editing C++. Hazard + evidence live in the profile; summarized here:",
        ]
        for u in unsafe:
            lines.append(f'//   {int(u["id"])}: {u["hazard"]} ({u["evidence"]})')
        lines += [
            "inline constexpr int kUnsafeIds[] = {" + ", ".join(str(int(u["id"])) for u in unsafe) + "};",
            f"inline constexpr int kUnsafeIdCount = {len(unsafe)};",
            "",
            "// Additive facts (consume or ignore): the FPC VMT header size - the byte",
            "// offset of a class's first declared virtual method (native/abi/fl_host_abi.h",
            "// holds the decode; the scraper re-derives it per install) - and the in-range",
            "// ids that hit the dispatcher's default branch (unhandled on this build).",
            f"inline constexpr int kVmtFirstMethodOffset = {int(dispatcher['vmt_first_method_offset'])};",
            "inline constexpr int kInertInRange[] = {"
            + ", ".join(str(int(i)) for i in dispatcher["inert_in_range"])
            + "};",
            "",
            "}  // namespace fl_profile",
            "",
            "// The static_assert wall: pins the FETCHED SDK HEADER's layout against the",
            "// layout scraped from FL's own record RTTI (the profile's structs block).",
            "// Compile-time only: a layout shift on a new FL version fails the build here,",
            "// never silently corrupts memory inside FL. Guarded so this header stays",
            "// SDK-free; the consuming TU defines FLMCP_ASSERT_STRUCTS after including",
            "// fp_plugclass.h.",
            "#ifdef FLMCP_ASSERT_STRUCTS",
            "#include <cstddef>",
        ]
        for name in ASSERTED_STRUCTS:
            record = structs[name]
            lines.append("")
            size_note = " with one note" if name == "TNotesParams" else ""
            lines.append(
                f'static_assert(sizeof({name}) == {int(record["size"])}, '
                f'"FL {name} is {int(record["size"])} bytes{size_note}");'
            )
            for field_doc in record["fields"]:
                fname, offset, ftype = field_doc["name"], int(field_doc["offset"]), field_doc["type"]
                lines.append(
                    f"static_assert(offsetof({name}, {fname}) == {offset}, "
                    f'"{name}.{fname} @{offset}");'
                )
                width = _TYPE_WIDTH.get(ftype)
                if width is not None:
                    lines.append(
                        f"static_assert(sizeof((({name} *)nullptr)->{fname}) == {width}, "
                        f'"{name}.{fname} is {width} bytes ({ftype} in FL\'s RTTI)");'
                    )
        lines += [
            "#endif  // FLMCP_ASSERT_STRUCTS",
            "",
            "#endif  // FLMCP_PROFILE_GENERATED_H",
            "",
        ]
        return "\n".join(lines)
    except GenError:
        raise
    except (KeyError, TypeError, ValueError) as exc:
        raise GenError(f"malformed profile document: {exc!r}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m fl_mcp.gen_layout",
        description="Emit the generated native ABI header from a capability profile.",
    )
    parser.add_argument("profile", type=Path, help="profile.json (the §A1 schema)")
    parser.add_argument("-o", "--output", type=Path, default=None, help="output header (default: stdout)")
    args = parser.parse_args(argv)
    try:
        doc = json.loads(args.profile.read_text())
        text = generate(doc)
    except (OSError, json.JSONDecodeError, GenError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.output is None:
        sys.stdout.write(text)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
